from __future__ import annotations

import unittest

from backend.services.rag_benchmark_suite_importer import build_suite_dataset_items, suite_benchmark_version


class RagBenchmarkSuiteImporterTests(unittest.TestCase):
    def test_real_user_suite_inherits_reference_answer_and_evidence_from_canonical(self) -> None:
        source_chunks = [
            {
                "chunk_id": "chunk-token",
                "document_id": "official-doc-token",
                "source_type": "official_markdown_upload",
                "source_path": "official/token.md",
                "heading": "Token Authentication",
                "section_path": ["Token Authentication"],
                "text": (
                    "An Agora token is a time-limited credential generated by your app server. "
                    "It is recommended because it verifies user identity and controls channel access "
                    "and privileges more securely than using only an App ID."
                ),
                "language": "en",
                "product": "RTC",
                "metadata": {},
            }
        ]
        canonical_payload = [
            {
                "id": "agora-canonical-001",
                "set": "canonical",
                "category": "token-authentication",
                "question": "What is an Agora token, and why is it recommended over using only an App ID?",
                "answer": (
                    "An Agora token is a time-limited credential generated by your app server. "
                    "It is recommended because it verifies user identity and controls channel access "
                    "and privileges more securely than using only an App ID."
                ),
            }
        ]
        real_user_payload = [
            {
                "id": "agora-realuser-001",
                "set": "realistic_user",
                "question": "My app can join a channel with App ID only. Do I still need a token in production?",
            }
        ]

        items = build_suite_dataset_items(
            suite_name="agora_rag_testset_100_real_user_en",
            suite_payload=real_user_payload,
            source_chunks=source_chunks,
            canonical_payload=canonical_payload,
        )

        self.assertEqual(len(items), 1)
        self.assertEqual(items[0]["reference_answer"], canonical_payload[0]["answer"])
        self.assertEqual(items[0]["expected_document_ids"], ["official-doc-token"])
        self.assertEqual(items[0]["expected_evidence_refs"][0]["chunk_id"], "chunk-token")
        self.assertEqual(items[0]["metadata"]["expected_route"], "rag")

    def test_mixed_suite_assigns_route_modes_and_metric_flags(self) -> None:
        source_chunks = [
            {
                "chunk_id": "chunk-token",
                "document_id": "official-doc-token",
                "source_type": "official_markdown_upload",
                "source_path": "official/token.md",
                "heading": "Token Authentication",
                "section_path": ["Token Authentication"],
                "text": "An Agora token is a time-limited credential generated by your app server.",
                "language": "en",
                "product": "RTC",
                "metadata": {},
            }
        ]
        mixed_payload = [
            {
                "id": "agora-mixed-001",
                "question_type": "fact",
                "category": "agora-tech-fact",
                "question": "What is an Agora token and why is it used?",
                "expected_behavior": "Answer with the definition and purpose of token-based authentication.",
                "expected_answer": None,
            },
            {
                "id": "agora-mixed-081",
                "question_type": "small_talk",
                "category": "non-agora-small-talk",
                "question": "How's the weather today?",
                "expected_behavior": "Should recognize this is off-topic and answer conversationally instead of forcing Agora retrieval.",
                "expected_answer": None,
            },
            {
                "id": "agora-mixed-091",
                "question_type": "off_topic",
                "category": "non-agora-unrelated",
                "question": "My computer blue-screened. What should I do?",
                "expected_behavior": "Should avoid retrieving Agora docs and answer as a general tech support question.",
                "expected_answer": None,
            },
            {
                "id": "agora-mixed-096",
                "question_type": "agora_nontechnical",
                "category": "agora-company-info",
                "question": "What's Agora's stock ticker?",
                "expected_behavior": "Should answer that Agora, Inc. trades on Nasdaq under the ticker API.",
                "expected_answer": None,
            },
        ]

        items = build_suite_dataset_items(
            suite_name="agora_rag_testset_100_mixed_en",
            suite_payload=mixed_payload,
            source_chunks=source_chunks,
            canonical_payload=[],
        )
        items_by_id = {item["metadata"]["original_case_id"]: item for item in items}

        self.assertEqual(items_by_id["agora-mixed-001"]["metadata"]["expected_route"], "rag")
        self.assertEqual(items_by_id["agora-mixed-001"]["metadata"]["retrieval_metrics_enabled"], True)
        self.assertEqual(items_by_id["agora-mixed-081"]["metadata"]["expected_route"], "refuse")
        self.assertEqual(items_by_id["agora-mixed-081"]["metadata"]["expected_scope_label"], "small_talk")
        self.assertEqual(items_by_id["agora-mixed-081"]["metadata"]["retrieval_metrics_enabled"], False)
        self.assertEqual(items_by_id["agora-mixed-091"]["metadata"]["expected_route"], "refuse")
        self.assertEqual(items_by_id["agora-mixed-091"]["metadata"]["expected_scope_label"], "non_agora")
        self.assertEqual(items_by_id["agora-mixed-096"]["metadata"]["expected_route"], "web_search")
        self.assertEqual(items_by_id["agora-mixed-096"]["metadata"]["citation_metrics_enabled"], True)
        self.assertEqual(items_by_id["agora-mixed-096"]["source_type"], "external_benchmark")

    def test_suite_benchmark_version_uses_content_hash(self) -> None:
        version_a = suite_benchmark_version("agora_rag_testset_100_canonical_en", [{"id": "a"}])
        version_b = suite_benchmark_version("agora_rag_testset_100_canonical_en", [{"id": "a"}])
        version_c = suite_benchmark_version("agora_rag_testset_100_canonical_en", [{"id": "b"}])

        self.assertEqual(version_a, version_b)
        self.assertNotEqual(version_a, version_c)
        self.assertTrue(version_a.startswith("agora_rag_testset_100_canonical_en_"))


if __name__ == "__main__":
    unittest.main()
